import Foundation

/// Labels for the menus, the settings window and alerts; what the characters say lives in the content pack.
enum UIText {
    case professionDeveloper, professionOffice, professionDesigner, professionMarketing, professionManager
    case reminderWater, reminderMove, reminderEyes, reminderHint
    case skills, remindNow, pauseReminders, resumeReminders, characters, showCompanion, hideCompanion, settings, quit
    /// "%@" is a time.
    case pausedUntil
    case offHours, quietNow, showingNow
    case minutes15, minutes30, hour1, hours2, restOfToday
    case reminderDone, snooze10, snooze30, skipOnce
    case tabCharacter, tabReminders, tabSchedule, tabBehavior, tabUpdates
    case language, volume
    /// "%@" is a number of minutes (or hours).
    case everyMinutes, minutesShort, hoursShort
    case tryNow, remindersExplain
    case workHours, workHoursOnly, from, to, quietHours, quietHoursOn, scheduleExplain
    case launchAtLogin, chatter, playWithWindows, playWithWindowsExplain, kickIcons, kickIconsExplain, openAutomation
    case appVersion, contentVersion, autoUpdate, checkNow, updatesExplain
    /// "%@" is the permission error code.
    case finderNotAllowed
    /// "%@" is a version number (the current one, or the one available).
    case checkUpdates, updateAvailable
    case upToDate, checkingUpdates, installingUpdate, updateFailed
    /// "%@" is the folder the app is in.
    case updateNoPermission
}

/// `key` in the current language, falling back to English; "%@" becomes `argument`.
func ui(_ key: UIText, _ argument: String = "") -> String {
    let text = uiTexts[Language.current]?[key] ?? uiTexts[.en]?[key] ?? ""
    return text.replacingOccurrences(of: "%@", with: argument)
}

